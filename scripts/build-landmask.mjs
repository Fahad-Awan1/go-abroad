// Generates src/js/three/landmask.js — a 1-bit equirectangular land/ocean bitmap
// (W x H) used by the dotted globe. Source: three.js example earth specular map
// (ocean = bright, land = dark). Run once: `node scripts/build-landmask.mjs`.
import sharp from 'sharp';
import fs from 'node:fs/promises';

const W = 256, H = 128;
const url = 'https://raw.githubusercontent.com/mrdoob/three.js/master/examples/textures/planets/earth_specular_2048.jpg';
const res = await fetch(url);
if (!res.ok) throw new Error(`download failed ${res.status}`);
const { data } = await sharp(Buffer.from(await res.arrayBuffer())).greyscale().resize(W, H, { fit: 'fill' }).raw().toBuffer({ resolveWithObject: true });

const bytes = new Uint8Array((W * H) / 8);
let land = 0;
for (let i = 0; i < W * H; i++) {
  if (data[i] < 110) { bytes[i >> 3] |= 1 << (i & 7); land++; }
}
const b64 = Buffer.from(bytes).toString('base64');
await fs.writeFile('src/js/three/landmask.js',
  `// Auto-generated by scripts/build-landmask.mjs — ${W}x${H} land bitmap (1 = land).\n` +
  `export const MASK_W = ${W};\nexport const MASK_H = ${H};\nexport const MASK = '${b64}';\n`);
console.log(`land pixels: ${land} / ${W * H}`);
